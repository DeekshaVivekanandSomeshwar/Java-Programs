package basicProgram;

public class ArithmaticOperator {

	public static void main(String[] args) {
		int a = 10;
		int b = 20;
		//Addition
		int add = a+b;
		System.out.println(add);
		//Subtraction
		int sub = b-a;
		System.out.println(sub);
		//Multiplication
		int mul = a*b;
		System.out.println(mul);
		//Division
		double div = a/b ;
		System.out.println(div);
		//Mod
		int mod = a%b ;
		System.out.println(mod);	

	}

}
